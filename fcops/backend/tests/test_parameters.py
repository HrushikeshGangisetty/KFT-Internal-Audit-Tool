MEDIA = tempfile.mkdtemp(prefix="wp8-media-")


def upload(name, text):
    return SimpleUploadedFile(name, text.encode())


@override_settings(MEDIA_ROOT=MEDIA)
class ParameterApiTests(TestCase):
    @classmethod
    def tearDownClass(cls):
        super().tearDownClass()
        shutil.rmtree(MEDIA, ignore_errors=True)

    def setUp(self):
        self.w = AccessWorld()
        self.tech = self.w.asm_member
        self.fw_lead = make_user("fw_lead", Role.DEPARTMENT_LEAD, self.w.firmware)
        self.fc = fcsvc.register_fc(fc_model=make_fc_model("ev"), actor=self.w.asm_head)

    def client_for(self, user):
        client = APIClient()
        client.force_authenticate(user)
        return client

    def _upload(self, client, text, name="dump.param", **extra):
        return client.post("/api/parameter-files/",
                           {"file": upload(name, text), **extra}, format="multipart")

    def evidence(self, client, file_id, kind, **extra):
        r = client.post("/api/config-evidence/", {"file": file_id, "kind": kind, **extra},
                        format="json")
        self.assertEqual(r.status_code, 201, r.data)
        return r.data

    def test_upload_parses_and_stores(self):
        r = self._upload(self.client_for(self.tech), SAMPLE_A, label="baseline")
        self.assertEqual(r.status_code, 201, r.content)
        self.assertEqual(r.data["parameter_count"], 5)
        self.assertEqual(r.data["label"], "baseline")
        self.assertEqual(ParameterFile.objects.get().uploaded_by, self.tech)
        self.assertTrue(AuditLogEntry.objects.filter(entity_type="ParameterFile").exists())

    def test_empty_or_unparseable_file_is_rejected(self):
        r = self._upload(self.client_for(self.tech), "# only a comment\n")
        self.assertEqual(r.status_code, 409, r.content)

    def test_same_file_twice_is_stored_once(self):
        client = self.client_for(self.tech)
        first = self._upload(client, SAMPLE_A, name="a.param")
        second = self._upload(client, SAMPLE_A, name="copy.param")
        self.assertEqual((first.status_code, second.status_code), (201, 200))
        self.assertTrue(second.data["already_stored"])
        self.assertEqual(second.data["id"], first.data["id"])
        self.assertEqual(ParameterFile.objects.count(), 1)

    def test_compare_two_uploads_without_storing_them(self):
        r = self.client_for(self.tech).post("/api/parameter-files/compare/", {
            "left_file": upload("a.param", SAMPLE_A),
            "right_file": upload("b.param", SAMPLE_B)}, format="multipart")
        self.assertEqual(r.status_code, 200, r.content)
        self.assertEqual(r.data["summary"]["changed"], 3)
        self.assertEqual(r.data["left_name"], "a.param")
        self.assertEqual(ParameterFile.objects.count(), 0)

    def test_compare_two_stored_files_and_needs_both_sides(self):
        client = self.client_for(self.tech)
        left = self._upload(client, SAMPLE_A, name="a.param", label="before").data
        right = self._upload(client, SAMPLE_B, name="b.param", label="after").data
        r = client.post("/api/parameter-files/compare/",
                        {"left": left["id"], "right": right["id"]}, format="json")
        self.assertEqual((r.status_code, r.data["left_name"]), (200, "before"))
        r = client.post("/api/parameter-files/compare/", {"left": left["id"]},
                        format="json")
        self.assertEqual(r.status_code, 409)

    def test_listing_does_not_ship_the_whole_parameter_set(self):
        client = self.client_for(self.tech)
        self._upload(client, SAMPLE_A)
        row = client.get("/api/parameter-files/").data["results"][0]
        self.assertNotIn("parameters", row)
        self.assertNotIn("raw_text", row)

    def test_scenario_4_three_kinds_byte_for_byte_and_compared(self):
        client = self.client_for(self.tech)
        texts = {"approved_baseline": SAMPLE_A,
                 "flashed_record": SAMPLE_A + "EXTRA_PARAM,1\n",
                 "readback": SAMPLE_B + "BROKEN LINE WITH NO VALUE\n"}
        ids = {}
        for kind, text in texts.items():
            f = self._upload(client, text, name=f"{kind}.param").data
            ids[kind] = self.evidence(client, f["id"], kind, fc=self.fc.pk,
                                      firmware_version="4.6.3",
                                      tool="Mission Planner export")["id"]
            body = b"".join(client.get(f["download_url"]).streaming_content)
            self.assertEqual(hashlib.sha256(body).hexdigest(), f["sha256"])
            self.assertEqual(body, text.encode())
        self.assertEqual(set(ConfigEvidence.objects.filter(fc=self.fc)
                             .values_list("kind", flat=True)), set(texts))
        r = client.post("/api/parameter-comparisons/", {
            "left_evidence": ids["approved_baseline"],
            "right_evidence": ids["readback"]}, format="json")
        self.assertEqual(r.status_code, 201, r.data)
        result = r.data["result"]
        self.assertEqual(result["summary"]["changed"], 3)
        self.assertEqual(len(result["warnings"]["right"]), 1)
        for verdict in ("safe", "unsafe", "is_safe", "verdict"):
            self.assertNotIn(verdict, result)
            self.assertNotIn(verdict, r.data)

    def test_baseline_approval_is_an_authenticated_action(self):
        client = self.client_for(self.tech)
        f = self._upload(client, SAMPLE_A).data
        ev = self.evidence(client, f["id"], "approved_baseline", fc=self.fc.pk)
        url = f"/api/config-evidence/{ev['id']}/approve-baseline/"
        self.assertEqual(client.post(url, {"revision": "r1"}, format="json")
                         .status_code, 409)
        lead = self.client_for(self.fw_lead)
        r = lead.post(url, {"revision": "r1", "scope": "rev-C boards"}, format="json")
        self.assertEqual(r.status_code, 200, r.data)
        self.assertEqual(r.data["approval"]["approved_by"], self.fw_lead.pk)

    def test_unknown_unit_evidence_can_be_associated_later(self):
        client = self.client_for(self.tech)
        f = self._upload(client, SAMPLE_B).data
        ev = self.evidence(client, f["id"], "readback", tool="field laptop")
        self.assertEqual(ev["unit_identity_confidence"], "unknown")
        r = client.post(f"/api/config-evidence/{ev['id']}/associate/", {
            "fc": self.fc.pk, "reason": "serial on the label photo"}, format="json")
        self.assertEqual(r.status_code, 201, r.data)
        self.assertEqual((r.data["fc"], r.data["supersedes"]), (self.fc.pk, ev["id"]))
        self.assertEqual(client.get(f"/api/config-evidence/{ev['id']}/")
                         .data["superseded_by"], r.data["id"])
        self.assertTrue(AuditLogEntry.objects.filter(
            entity_type="ConfigEvidence", entity_id=str(r.data["id"]),
            note="serial on the label photo").exists())

    def test_newer_evidence_supersedes_without_overwriting(self):
        client = self.client_for(self.tech)
        a = self._upload(client, SAMPLE_A, name="a").data
        b = self._upload(client, SAMPLE_B, name="b").data
        first = self.evidence(client, a["id"], "readback", fc=self.fc.pk)
        second = self.evidence(client, b["id"], "readback", fc=self.fc.pk)
        self.assertEqual(second["supersedes"], first["id"])
        self.assertEqual(ConfigEvidence.objects.get(pk=first["id"]).file_id, a["id"])

    def test_issue_shows_versions_from_linked_evidence_with_capture_time(self):
        client = self.client_for(self.w.asm_head)
        f = self._upload(client, SAMPLE_A).data
        ev = self.evidence(client, f["id"], "readback", fc=self.fc.pk,
                           firmware_version="4.6.3-kft2",
                           captured_at="2026-10-01T10:00:00+05:30")
        issue = self.w.asm_issue
        r = client.post(f"/api/issues/{issue.pk}/evidence/", {"evidence": ev["id"]},
                        format="json")
        self.assertEqual(r.status_code, 201, r.data)
        row = r.data["versions_at_time"][0]
        self.assertEqual((row["source"], row["firmware_version"]),
                         ("linked", "4.6.3-kft2"))
        self.assertTrue(row["captured_at"])

    def test_without_fc_scope_files_and_evidence_are_hidden(self):
        client = self.client_for(self.tech)
        f = self._upload(client, SAMPLE_A).data
        self.evidence(client, f["id"], "readback", fc=self.fc.pk)
        outsider = self.client_for(self.w.admin)  # no department, not a head
        self.assertEqual(outsider.get("/api/parameter-files/").data["count"], 0)
        self.assertEqual(outsider.get(f"/api/parameter-files/{f['id']}/download/")
                         .status_code, 404)
        self.assertEqual(outsider.get("/api/config-evidence/").data["count"], 0)

    def test_linked_unit_appears_on_the_fc_timeline_and_issues_tab(self):
        other = fcsvc.register_fc(fc_model=make_fc_model("ev"), actor=self.w.asm_head)
        issvc.link_unit(self.w.asm_issue, fc=other, actor=self.w.asm_head,
                        reason="same harness batch")
        client = self.client_for(self.w.asm_head)
        kinds = [e["kind"] for e in client.get(f"/api/fcs/{other.pk}/timeline/").data]
        self.assertIn("ISSUE_LINKED", kinds)
        ids = [i["id"] for i in client.get(f"/api/fcs/{other.pk}/issues/").data]
        self.assertEqual(ids, [self.w.asm_issue.pk])
