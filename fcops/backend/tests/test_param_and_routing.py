class RoutingTestCase(TestCase):
    def setUp(self):
        self.hw = make_department("assembly", Department.KIND_HARDWARE)
        self.testing = make_department("testing", Department.KIND_TESTING)
        self.tech = make_user("tech", Role.TECHNICIAN, self.hw)
        self.tester = make_user("tester", Role.TEST_ENGINEER, self.testing)
        self.manager = make_user("mgr", Role.MANAGER, self.testing)
        self.model = make_fc_model()

    def client_for(self, user):
        client = APIClient()
        r = client.post("/api/auth/token/",
                        {"username": user.username, "password": PASSWORD},
                        format="json")
        client.credentials(HTTP_AUTHORIZATION=f"Bearer {r.data['access']}")
        return client

    def _advance(self, fc, until):
        while fc.current_stage != until:
            fcsvc.start_stage(fc, actor=self.tech)
            fcsvc.complete_stage(fc, passed=True, actor=self.tech)
            fc.refresh_from_db()


class FailureRoutingTests(RoutingTestCase):
    def test_bench_testing_gates_ground_testing(self):
        """Confirmed with the Testing lead: ground testing only follows a
        passed bench test, so that return route is standard."""
        self.assertIn(Stage.BENCH_TESTING, earlier_stages(Stage.GROUND_TESTING))
        self.assertTrue(is_standard_rework(Stage.GROUND_TESTING,
                                           Stage.BENCH_TESTING))

    def test_failing_a_stage_can_route_the_fc_back_in_one_action(self):
        fc = fcsvc.register_fc(fc_model=self.model, actor=self.tech)
        self._advance(fc, Stage.GROUND_TESTING)
        fcsvc.start_stage(fc, actor=self.tester)

        record = fcsvc.complete_stage(
            fc, passed=False, actor=self.tester, notes="No GPS fix",
            return_to_stage=Stage.MACHINE_ASSEMBLY,
            return_reason="Connector joint suspected")
        fc.refresh_from_db()

        self.assertEqual(record.status, StageStatus.FAILED)
        self.assertEqual(fc.current_stage, Stage.MACHINE_ASSEMBLY)
        rework = ReworkRecord.objects.get(stage_record=record)
        self.assertEqual(rework.return_to_stage, Stage.MACHINE_ASSEMBLY)
        self.assertEqual(rework.outcome, ReworkRecord.OUTCOME_PENDING)
        # The failed attempt is still there.
        self.assertEqual(
            fc.stage_records.filter(stage=Stage.GROUND_TESTING,
                                    status=StageStatus.FAILED).count(), 1)

    def test_failure_without_routing_leaves_the_fc_where_it_is(self):
        fc = fcsvc.register_fc(fc_model=self.model, actor=self.tech)
        self._advance(fc, Stage.QC)
        fcsvc.start_stage(fc, actor=self.tech)
        fcsvc.complete_stage(fc, passed=False, actor=self.tech)
        fc.refresh_from_db()
        self.assertEqual(fc.current_stage, Stage.QC)
        self.assertFalse(ReworkRecord.objects.exists())

    def test_any_earlier_stage_is_reachable_with_a_reason(self):
        """A late failure can originate anywhere upstream."""
        fc = fcsvc.register_fc(fc_model=self.model, actor=self.tech)
        self._advance(fc, Stage.GROUND_TESTING)
        fcsvc.start_stage(fc, actor=self.tester)
        fcsvc.complete_stage(
            fc, passed=False, actor=self.tester,
            return_to_stage=Stage.FABRICATION,
            return_reason="Track damage visible on the bare PCB")
        fc.refresh_from_db()
        self.assertEqual(fc.current_stage, Stage.FABRICATION)

    def test_exceptional_route_is_recorded_as_such(self):
        fc = fcsvc.register_fc(fc_model=self.model, actor=self.tech)
        self._advance(fc, Stage.GROUND_TESTING)
        fcsvc.start_stage(fc, actor=self.tester)
        fcsvc.complete_stage(fc, passed=False, actor=self.tester,
                             return_to_stage=Stage.FABRICATION,
                             return_reason="PCB track damage")
        note = AuditLogEntry.objects.filter(
            entity_type="ReworkRecord").first().note
        self.assertIn("EXCEPTIONAL", note)

        fc2 = fcsvc.register_fc(fc_model=self.model, actor=self.tech)
        self._advance(fc2, Stage.GROUND_TESTING)
        fcsvc.start_stage(fc2, actor=self.tester)
        fcsvc.complete_stage(fc2, passed=False, actor=self.tester,
                             return_to_stage=Stage.BENCH_TESTING,
                             return_reason="Re-run the bench suite")
        note = AuditLogEntry.objects.filter(
            entity_type="ReworkRecord").first().note
        self.assertIn("standard route", note)

    def test_exceptional_route_requires_a_reason(self):
        fc = fcsvc.register_fc(fc_model=self.model, actor=self.tech)
        self._advance(fc, Stage.GROUND_TESTING)
        fcsvc.start_stage(fc, actor=self.tester)
        with self.assertRaises(WorkflowError) as ctx:
            fcsvc.complete_stage(fc, passed=False, actor=self.tester,
                                 return_to_stage=Stage.FABRICATION)
        self.assertEqual(ctx.exception.code, "reason_required")

    def test_cannot_route_forward(self):
        fc = fcsvc.register_fc(fc_model=self.model, actor=self.tech)
        self._advance(fc, Stage.QC)
        fcsvc.start_stage(fc, actor=self.tech)
        with self.assertRaises(WorkflowError) as ctx:
            fcsvc.complete_stage(fc, passed=False, actor=self.tech,
                                 return_to_stage=Stage.GROUND_TESTING,
                                 return_reason="nope")
        self.assertEqual(ctx.exception.code, "not_an_earlier_stage")

    def test_routing_through_the_api_and_the_options_offered(self):
        client = self.client_for(self.tester)
        fc = fcsvc.register_fc(fc_model=self.model, actor=self.tech)
        self._advance(fc, Stage.BENCH_TESTING)
        fcsvc.start_stage(fc, actor=self.tester)

        detail = client.get(f"/api/fcs/{fc.id}/").data
        options = {o["value"]: o["standard"] for o in detail["return_options"]}
        self.assertIn(str(Stage.FIRMWARE), options)
        self.assertNotIn(str(Stage.GROUND_TESTING), options)
        self.assertTrue(options[str(Stage.FIRMWARE)])

        r = client.post(f"/api/fcs/{fc.id}/fail_stage/",
                        {"notes": "motor 3 no response",
                         "return_to_stage": Stage.MECHANICAL_ASSEMBLY,
                         "return_reason": "Loose motor lead"}, format="json")
        self.assertEqual(r.status_code, 200, r.content)
        self.assertEqual(r.data["fc"]["current_stage"],
                         Stage.MECHANICAL_ASSEMBLY)

    def test_timeline_shows_where_the_fc_was_returned_to(self):
        fc = fcsvc.register_fc(fc_model=self.model, actor=self.tech)
        self._advance(fc, Stage.GROUND_TESTING)
        fcsvc.start_stage(fc, actor=self.tester)
        fcsvc.complete_stage(fc, passed=False, actor=self.tester,
                             return_to_stage=Stage.FIRMWARE,
                             return_reason="Parameter profile wrong")
        titles = [e.title for e in fc.events.all()]
        self.assertTrue(any("Returned to Firmware" in t for t in titles), titles)


class ParameterParsingTests(TestCase):
    def test_parses_comma_separated_values(self):
        params, skipped = param_parser.parse(SAMPLE_A)
        self.assertEqual(params["ANGLE_MAX"], 3000)
        self.assertEqual(params["COMPASS_DEC"], -0.01028054)
        self.assertEqual(skipped, [])

    def test_accepts_whitespace_and_tab_separators(self):
        params, _ = param_parser.parse("ANGLE_MAX 3000\nAVOID_MARGIN\t10\n")
        self.assertEqual(params, {"ANGLE_MAX": 3000.0, "AVOID_MARGIN": 10.0})

    def test_ignores_comments_and_blank_lines(self):
        params, skipped = param_parser.parse("# header\n\nA,1\n// note\nB,2\n")
        self.assertEqual(set(params), {"A", "B"})
        self.assertEqual(skipped, [])

    def test_reports_unreadable_lines_rather_than_dropping_them(self):
        params, skipped = param_parser.parse("GOOD,1\nBROKEN_LINE\nALSO,notanumber\n")
        self.assertEqual(set(params), {"GOOD"})
        self.assertEqual(len(skipped), 2)
        self.assertEqual(skipped[0]["line"], 2)

    def test_values_are_rendered_the_way_the_file_wrote_them(self):
        params, _ = param_parser.parse("INT,3000\nFLOAT,0.9825713\nNEG,-300\n")
        result = param_parser.compare(params, {"INT": 1, "FLOAT": 1.0, "NEG": 1})
        rendered = {c["name"]: c["left"] for c in result["changed"]}
        self.assertEqual(rendered["INT"], "3000")
        self.assertEqual(rendered["FLOAT"], "0.9825713")
        self.assertEqual(rendered["NEG"], "-300")

    def test_groups_strip_the_instance_number(self):
        self.assertEqual(param_parser.group_of("BATT2_CAPACITY"), "BATT")
        self.assertEqual(param_parser.group_of("SERVO10_FUNCTION"), "SERVO")
        self.assertEqual(param_parser.group_of("EK3_ENABLE"), "EK")
        self.assertEqual(param_parser.group_of("ANGLE_MAX"), "ANGLE")


class ParameterCompareTests(TestCase):
    def setUp(self):
        self.left, _ = param_parser.parse(SAMPLE_A)
        self.right, _ = param_parser.parse(SAMPLE_B)

    def test_reports_changed_added_and_removed(self):
        result = param_parser.compare(self.left, self.right)
        changed = {c["name"] for c in result["changed"]}
        self.assertEqual(changed, {"AVOID_MARGIN", "COMPASS_DEC", "BATT_CAPACITY"})
        self.assertEqual([c["name"] for c in result["only_in_left"]], ["ONLY_IN_A"])
        self.assertEqual([c["name"] for c in result["only_in_right"]], ["ONLY_IN_B"])
        self.assertEqual(result["summary"]["identical"], 1)

    def test_delta_is_signed_and_readable(self):
        result = param_parser.compare(self.left, self.right)
        margin = next(c for c in result["changed"] if c["name"] == "AVOID_MARGIN")
        self.assertEqual(margin["left"], "10")
        self.assertEqual(margin["right"], "7")
        self.assertEqual(margin["delta"], "-3")

    def test_tolerance_marks_float_noise_without_hiding_it(self):
        result = param_parser.compare(self.left, self.right, tolerance=1e-4)
        by_name = {c["name"]: c for c in result["changed"]}
        self.assertTrue(by_name["COMPASS_DEC"]["negligible"])
        self.assertFalse(by_name["BATT_CAPACITY"]["negligible"])
        # Still present — the operator decides, the tool does not hide data.
        self.assertIn("COMPASS_DEC", by_name)
        self.assertEqual(result["summary"]["negligible"], 1)

    def test_identical_files_report_no_differences(self):
        result = param_parser.compare(self.left, dict(self.left))
        self.assertEqual(result["summary"]["changed"], 0)
        self.assertEqual(result["summary"]["only_in_left"], 0)
        self.assertEqual(result["summary"]["identical"], len(self.left))


class ParameterApiTests(RoutingTestCase):
    def _upload(self, client, text, name="dump.param", **extra):
        from django.core.files.uploadedfile import SimpleUploadedFile
        return client.post("/api/parameter-files/",
                           {"file": SimpleUploadedFile(name, text.encode()),
                            **extra}, format="multipart")

    def test_upload_parses_and_stores(self):
        client = self.client_for(self.tech)
        r = self._upload(client, SAMPLE_A, label="baseline")
        self.assertEqual(r.status_code, 201, r.content)
        self.assertEqual(r.data["parameter_count"], 5)
        self.assertEqual(r.data["label"], "baseline")
        self.assertEqual(ParameterFile.objects.get().uploaded_by, self.tech)

    def test_upload_is_audited(self):
        self._upload(self.client_for(self.tech), SAMPLE_A)
        self.assertTrue(AuditLogEntry.objects.filter(
            entity_type="ParameterFile").exists())

    def test_empty_or_unparseable_file_is_rejected(self):
        r = self._upload(self.client_for(self.tech), "# only a comment\n")
        self.assertEqual(r.status_code, 409, r.content)

    def test_compare_two_uploads_without_storing_them(self):
        from django.core.files.uploadedfile import SimpleUploadedFile
        client = self.client_for(self.tester)
        r = client.post("/api/parameter-files/compare/", {
            "left_file": SimpleUploadedFile("a.param", SAMPLE_A.encode()),
            "right_file": SimpleUploadedFile("b.param", SAMPLE_B.encode()),
        }, format="multipart")
        self.assertEqual(r.status_code, 200, r.content)
        self.assertEqual(r.data["summary"]["changed"], 3)
        self.assertEqual(r.data["left_name"], "a.param")
        self.assertEqual(ParameterFile.objects.count(), 0)

    def test_compare_two_stored_files(self):
        client = self.client_for(self.tech)
        left = self._upload(client, SAMPLE_A, name="a.param", label="before").data
        right = self._upload(client, SAMPLE_B, name="b.param", label="after").data
        r = client.post("/api/parameter-files/compare/",
                        {"left": left["id"], "right": right["id"]}, format="json")
        self.assertEqual(r.status_code, 200, r.content)
        self.assertEqual(r.data["left_name"], "before")
        self.assertEqual(r.data["summary"]["changed"], 3)

    def test_compare_needs_both_sides(self):
        client = self.client_for(self.tech)
        stored = self._upload(client, SAMPLE_A).data
        r = client.post("/api/parameter-files/compare/",
                        {"left": stored["id"]}, format="json")
        self.assertEqual(r.status_code, 409, r.content)

    def test_dump_attached_to_an_fc_appears_in_its_history(self):
        fc = fcsvc.register_fc(fc_model=self.model, actor=self.tech)
        client = self.client_for(self.tech)
        self._upload(client, SAMPLE_A, fc=fc.id)
        self.assertEqual(fc.parameter_files.count(), 1)

    def test_listing_does_not_ship_the_whole_parameter_set(self):
        """The list is rendered on a slow link; it must stay small."""
        client = self.client_for(self.tech)
        self._upload(client, SAMPLE_A)
        r = client.get("/api/parameter-files/")
        self.assertEqual(r.status_code, 200)
        self.assertNotIn("parameters", r.data["results"][0])
        self.assertNotIn("raw_text", r.data["results"][0])


class QueryBudgetTests(RoutingTestCase):
    """Latency on a hosted database is dominated by round trips, so query
    counts are a correctness property here, not a micro-optimisation. These
    budgets fail loudly if an N+1 creeps back in."""

    def setUp(self):
        super().setUp()
        for _ in range(6):
            fc = fcsvc.register_fc(fc_model=self.model, actor=self.tech)
            fcsvc.start_stage(fc, actor=self.tech)
            fcsvc.complete_stage(fc, passed=True, actor=self.tech)
        self.fc = fc

    def test_fc_list_cost_does_not_grow_with_the_number_of_fcs(self):
        """The property that matters is flatness: doubling the rows must not
        add queries. An exact number would break on any harmless change."""
        from django.test.utils import CaptureQueriesContext
        from django.db import connection

        client = self.client_for(self.tech)
        with CaptureQueriesContext(connection) as small:
            client.get("/api/fcs/")
        for _ in range(8):
            fcsvc.register_fc(fc_model=self.model, actor=self.tech)
        with CaptureQueriesContext(connection) as large:
            client.get("/api/fcs/")
        self.assertEqual(len(small), len(large),
                         "FC list gained queries as rows were added")
        self.assertLessEqual(len(large), 6)

    def test_fc_detail_page_is_one_request_within_a_fixed_budget(self):
        from django.test.utils import CaptureQueriesContext
        from django.db import connection

        client = self.client_for(self.tech)
        response = client.get(f"/api/fcs/{self.fc.id}/full/")
        self.assertEqual(response.status_code, 200)
        for key in ("fc", "timeline", "stage_records", "issues"):
            self.assertIn(key, response.data)
        with CaptureQueriesContext(connection) as ctx:
            client.get(f"/api/fcs/{self.fc.id}/full/")
        self.assertLessEqual(len(ctx), 10, "FC detail page query budget exceeded")

    def test_detail_cost_does_not_grow_with_stage_attempts_or_issues(self):
        from django.test.utils import CaptureQueriesContext
        from django.db import connection
        from issues import services as issvc

        client = self.client_for(self.tech)
        with CaptureQueriesContext(connection) as before:
            client.get(f"/api/fcs/{self.fc.id}/full/")

        for _ in range(3):
            fcsvc.start_stage(self.fc, actor=self.tech)
            fcsvc.complete_stage(self.fc, passed=True, actor=self.tech)
            self.fc.refresh_from_db()
        for n in range(3):
            issvc.create_issue(fc=self.fc, title=f"issue {n}", symptoms="s",
                               actor=self.tech, assigned_department=self.hw)

        with CaptureQueriesContext(connection) as after:
            client.get(f"/api/fcs/{self.fc.id}/full/")
        self.assertEqual(len(before), len(after),
                         "FC detail gained queries as history grew")

    def test_dashboard_is_cached_between_loads(self):
        from django.core.cache import cache
        cache.clear()
        client = self.client_for(self.manager)
        first = client.get("/api/dashboard/summary/")
        self.assertFalse(first.data["cached"])
        with self.assertNumQueries(1):
            second = client.get("/api/dashboard/summary/")
        self.assertTrue(second.data["cached"])
        self.assertEqual(first.data["fc_total"], second.data["fc_total"])

    def test_dashboard_cache_can_be_bypassed(self):
        from django.core.cache import cache
        cache.clear()
        client = self.client_for(self.manager)
        client.get("/api/dashboard/summary/")
        fresh = client.get("/api/dashboard/summary/?fresh=1")
        self.assertFalse(fresh.data["cached"])
